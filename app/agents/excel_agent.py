from app.db.database import get_db

logger = logging.getLogger(__name__)

EXPORTS_DIR = "exports"


# ---------------------------------------------------------------------------
# Style helpers
# ---------------------------------------------------------------------------

def _header_font() -> Font:
    return Font(name="Calibri", bold=True, color="FFFFFF", size=11)


def _header_fill() -> PatternFill:
    return PatternFill(fill_type="solid", fgColor="1F4E79")


def _subheader_fill() -> PatternFill:
    return PatternFill(fill_type="solid", fgColor="2E75B6")


def _accent_fill() -> PatternFill:
    return PatternFill(fill_type="solid", fgColor="D6E4F0")


def _thin_border() -> Border:
    side = Side(style="thin", color="BFBFBF")
    return Border(left=side, right=side, top=side, bottom=side)


def _apply_header(cell, text: str, fill=None) -> None:
    cell.value = text
    cell.font = _header_font()
    cell.fill = fill or _header_fill()
    cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
    cell.border = _thin_border()


def _apply_label(cell, text: str) -> None:
    cell.value = text
    cell.font = Font(name="Calibri", bold=True, size=10)
    cell.alignment = Alignment(horizontal="left", vertical="center")
    cell.border = _thin_border()


def _apply_value(cell, value, number_format: str = "#,##0.00") -> None:
    cell.value = value
    cell.font = Font(name="Calibri", size=10)
    cell.number_format = number_format
    cell.alignment = Alignment(horizontal="right", vertical="center")
    cell.border = _thin_border()


def _apply_accent(cell) -> None:
    cell.fill = _accent_fill()


