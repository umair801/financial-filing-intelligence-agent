def build_dcf_export(ticker: str, filing_id: Optional[str] = None) -> dict:
    """
    Fetch the latest extraction for a ticker, build DCF scaffold, save to exports/.
    If filing_id is provided, use that specific filing.
    Returns a dict with file path and status.
    """
    os.makedirs(EXPORTS_DIR, exist_ok=True)
    db = next(get_db())

    try:
        # Fetch latest extraction for ticker
        if filing_id:
            query = """
                SELECT
                    e.capital_structure_changes,
                    e.contract_awards,
                    e.capex_guidance,
                    e.going_concern_flag,
                    e.undisclosed_counterparties,
                    r.ticker,
                    r.company_name,
                    r.filing_type,
                    r.filed_date,
                    r.id
                FROM filings_extractions e
                JOIN filings_raw r ON r.id = e.filing_id
                WHERE r.ticker = :ticker AND r.id = :filing_id
                LIMIT 1
            """
            row = db.execute(text(query), {"ticker": ticker, "filing_id": filing_id}).fetchone()
        else:
            query = """
                SELECT
                    e.capital_structure_changes,
                    e.contract_awards,
                    e.capex_guidance,
                    e.going_concern_flag,
                    e.undisclosed_counterparties,
                    r.ticker,
                    r.company_name,
                    r.filing_type,
                    r.filed_date,
                    r.id
                FROM filings_extractions e
                JOIN filings_raw r ON r.id = e.filing_id
                WHERE r.ticker = :ticker
                ORDER BY r.filed_date DESC
                LIMIT 1
            """
            row = db.execute(text(query), {"ticker": ticker}).fetchone()

        if not row:
            return {"success": False, "error": f"No extraction found for ticker {ticker}"}

        (
            capital_structure_changes,
            contract_awards,
            capex_guidance,
            going_concern_flag,
            undisclosed_counterparties,
            db_ticker,
            company_name,
            filing_type,
            filing_date,
            db_filing_id
        ) = row

        import json

        def _parse(val):
            if isinstance(val, str):
                try:
                    return json.loads(val)
                except Exception:
                    return val
            return val or {}

        extraction = {
            "capital_structure_changes": _parse(capital_structure_changes),
            "contract_awards": _parse(contract_awards),
            "capex_guidance": _parse(capex_guidance),
            "going_concern_flag": going_concern_flag or False,
            "undisclosed_counterparties": _parse(undisclosed_counterparties),
        }

        filing_meta = {
            "company_name": company_name or ticker,
            "filing_type": filing_type or "N/A",
            "filing_date": str(filing_date) if filing_date else "N/A",
        }

        # Build workbook
        wb = openpyxl.Workbook()
        wb.remove(wb.active)  # Remove default sheet

        ws_summary = wb.create_sheet("Summary")
        ws_dcf = wb.create_sheet("DCF Model")
        ws_signals = wb.create_sheet("Filing Signals")

        _build_summary_sheet(ws_summary, ticker, extraction, filing_meta)
        _build_dcf_sheet(ws_dcf, ticker, extraction)
        _build_signals_sheet(ws_signals, extraction)

        # Save with timestamp
        timestamp = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
        filename = f"{ticker}_DCF_{timestamp}.xlsx"
        filepath = os.path.join(EXPORTS_DIR, filename)
        wb.save(filepath)

        logger.info(f"DCF export saved: {filepath}")
        return {
            "success": True,
            "file": filepath,
            "ticker": ticker,
            "filing_id": str(db_filing_id),
            "company": filing_meta["company_name"],
            "filing_type": filing_meta["filing_type"],
            "filing_date": filing_meta["filing_date"],
        }

    except Exception as e:
        logger.error(f"DCF export failed for {ticker}: {e}")
        return {"success": False, "error": str(e)}

    finally:
        db.close()


def run_excel_pipeline(tickers: list) -> dict:
    """
    Run DCF export for a list of tickers.
    Returns summary of results.
    """
    results = {"exported": 0, "failed": 0, "files": []}

    for ticker in tickers:
        result = build_dcf_export(ticker)
        if result.get("success"):
            results["exported"] += 1
            results["files"].append(result["file"])
        else:
            results["failed"] += 1
            logger.error(f"Export failed for {ticker}: {result.get('error')}")

    return results