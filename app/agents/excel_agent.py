def _build_summary_sheet(ws, ticker: str, extraction: dict, filing_meta: dict) -> None:
    """Cover sheet: company overview and filing metadata."""
    ws.title = "Summary"
    ws.column_dimensions["A"].width = 30
    ws.column_dimensions["B"].width = 50

    # Title block
    ws.merge_cells("A1:B1")
    title_cell = ws["A1"]
    title_cell.value = f"Financial Filing Intelligence Report — {ticker}"
    title_cell.font = Font(name="Calibri", bold=True, size=14, color="FFFFFF")
    title_cell.fill = _header_fill()
    title_cell.alignment = Alignment(horizontal="center", vertical="center")
    ws.row_dimensions[1].height = 30

    ws.merge_cells("A2:B2")
    subtitle = ws["A2"]
    subtitle.value = "Generated by Datawebify | filings.datawebify.com"
    subtitle.font = Font(name="Calibri", italic=True, size=10, color="595959")
    subtitle.alignment = Alignment(horizontal="center")

    # Metadata rows
    meta_rows = [
        ("Ticker", ticker),
        ("Company", filing_meta.get("company_name", "N/A")),
        ("Filing Type", filing_meta.get("filing_type", "N/A")),
        ("Filing Date", filing_meta.get("filing_date", "N/A")),
        ("Report Generated", datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")),
        ("Going Concern Flag", "YES" if extraction.get("going_concern_flag") else "NO"),
    ]

    for i, (label, value) in enumerate(meta_rows, start=4):
        _apply_label(ws.cell(row=i, column=1), label)
        cell = ws.cell(row=i, column=2)
        cell.value = str(value)
        cell.font = Font(name="Calibri", size=10)
        cell.border = _thin_border()
        if label == "Going Concern Flag" and value == "YES":
            cell.font = Font(name="Calibri", size=10, color="FF0000", bold=True)


def _build_dcf_sheet(ws, ticker: str, extraction: dict) -> None:
    """DCF scaffold with revenue, capex, and WACC assumptions."""
    ws.title = "DCF Model"
    ws.column_dimensions["A"].width = 32
    for col in ["B", "C", "D", "E", "F"]:
        ws.column_dimensions[col].width = 16

    years = ["Year 1", "Year 2", "Year 3", "Year 4", "Year 5"]

    # Header row
    _apply_header(ws["A1"], "DCF SCAFFOLD — " + ticker)
    for i, yr in enumerate(years, start=2):
        _apply_header(ws.cell(row=1, column=i), yr)

    # --- Revenue section ---
    ws.merge_cells("A2:F2")
    ws["A2"].value = "REVENUE INPUTS"
    ws["A2"].font = Font(name="Calibri", bold=True, size=10, color="FFFFFF")
    ws["A2"].fill = _subheader_fill()
    ws["A2"].alignment = Alignment(horizontal="left")

    capex_guidance = extraction.get("capex_guidance") or {}
    guidance_amount = capex_guidance.get("amount") if isinstance(capex_guidance, dict) else None

    revenue_rows = [
        ("Base Revenue (extracted/manual, $M)", guidance_amount or 0),
        ("Revenue Growth Rate (%)", 0.05),
        ("Projected Revenue ($M)", None),
    ]

    row = 3
    for label, base_val in revenue_rows:
        _apply_label(ws.cell(row=row, column=1), label)
        for col in range(2, 7):
            cell = ws.cell(row=row, column=col)
            if label == "Projected Revenue ($M)":
                prev_col = get_column_letter(col - 1) if col > 2 else None
                if col == 2:
                    formula = f"=B3*(1+B4)"
                else:
                    prev = get_column_letter(col - 1)
                    formula = f"={prev}{row-1}*(1+{get_column_letter(col)}4)"
                _apply_value(cell, formula if col > 2 else f"=B3*(1+B4)")
            else:
                _apply_value(cell, base_val if col == 2 else None)
            _apply_accent(cell)
        row += 1

    # --- Capex section ---
    row += 1
    ws.merge_cells(f"A{row}:F{row}")
    ws[f"A{row}"].value = "CAPEX INPUTS"
    ws[f"A{row}"].font = Font(name="Calibri", bold=True, size=10, color="FFFFFF")
    ws[f"A{row}"].fill = _subheader_fill()
    ws[f"A{row}"].alignment = Alignment(horizontal="left")
    row += 1

    capex_rows = [
        ("Capex ($M)", guidance_amount or 0),
        ("Capex as % of Revenue", 0.08),
        ("D&A ($M)", 0),
    ]
    for label, base_val in capex_rows:
        _apply_label(ws.cell(row=row, column=1), label)
        for col in range(2, 7):
            cell = ws.cell(row=row, column=col)
            _apply_value(cell, base_val if col == 2 else None)
        row += 1

    # --- FCF section ---
    row += 1
    ws.merge_cells(f"A{row}:F{row}")
    ws[f"A{row}"].value = "FREE CASH FLOW"
    ws[f"A{row}"].font = Font(name="Calibri", bold=True, size=10, color="FFFFFF")
    ws[f"A{row}"].fill = _subheader_fill()
    ws[f"A{row}"].alignment = Alignment(horizontal="left")
    row += 1

    fcf_rows = [
        ("EBIT Margin (%)", 0.20),
        ("Tax Rate (%)", 0.21),
        ("NOPAT ($M)", None),
        ("Less: Capex ($M)", None),
        ("Plus: D&A ($M)", None),
        ("Free Cash Flow ($M)", None),
    ]
    for label, base_val in fcf_rows:
        _apply_label(ws.cell(row=row, column=1), label)
        for col in range(2, 7):
            cell = ws.cell(row=row, column=col)
            _apply_value(cell, base_val if col == 2 else None)
        row += 1

    # --- WACC / Terminal Value section ---
    row += 1
    ws.merge_cells(f"A{row}:F{row}")
    ws[f"A{row}"].value = "WACC & TERMINAL VALUE"
    ws[f"A{row}"].font = Font(name="Calibri", bold=True, size=10, color="FFFFFF")
    ws[f"A{row}"].fill = _subheader_fill()
    ws[f"A{row}"].alignment = Alignment(horizontal="left")
    row += 1

    wacc_rows = [
        ("WACC (%)", 0.10),
        ("Terminal Growth Rate (%)", 0.025),
        ("Terminal Value ($M)", None),
        ("PV of Terminal Value ($M)", None),
        ("Enterprise Value ($M)", None),
    ]
    for label, base_val in wacc_rows:
        _apply_label(ws.cell(row=row, column=1), label)
        for col in range(2, 7):
            cell = ws.cell(row=row, column=col)
            _apply_value(cell, base_val if col == 2 else None)
        row += 1


def _build_signals_sheet(ws, extraction: dict) -> None:
    """Extracted financial signals from GPT-4o."""
    ws.title = "Filing Signals"
    ws.column_dimensions["A"].width = 30
    ws.column_dimensions["B"].width = 60

    _apply_header(ws["A1"], "SIGNAL TYPE")
    _apply_header(ws["B1"], "EXTRACTED VALUE")
    ws.row_dimensions[1].height = 22

    signals = [
        ("Going Concern Flag", str(extraction.get("going_concern_flag", False))),
        ("Capital Structure Changes", str(extraction.get("capital_structure_changes", "None"))),
        ("Contract Awards", str(extraction.get("contract_awards", "None"))),
        ("Capex Guidance", str(extraction.get("capex_guidance", "None"))),
        ("Undisclosed Counterparties", str(extraction.get("undisclosed_counterparties", "None"))),
    ]

    for i, (signal, value) in enumerate(signals, start=2):
        _apply_label(ws.cell(row=i, column=1), signal)
        cell = ws.cell(row=i, column=2)
        cell.value = value
        cell.font = Font(name="Calibri", size=10)
        cell.alignment = Alignment(wrap_text=True, vertical="top")
        cell.border = _thin_border()
        ws.row_dimensions[i].height = 40


